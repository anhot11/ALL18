    /**
     * Obtiene una palabra basada en un caracter o hash de foto
     */
    fun getWordFromPhoto(photoUrl: String, salt: Int = 0): String {
        if (photoUrl.isEmpty()) {
            val idx = (salt * 31).absoluteValue % WORDS.size
            return WORDS[idx]
        }
        val charCode = photoUrl.last().code + photoUrl.first().code * 19 + salt * 41
        val idx = charCode.absoluteValue % WORDS.size
        return WORDS[idx]
    }

